const TEXTS_BY_LANGUAGE: Record<LanguageCode, Texts> = { es: ES, en: EN }

/** The interface texts in the current language. */
export function getTexts(): Texts {
	return TEXTS_BY_LANGUAGE[LanguageService.get()]
}

/** Replace each {key} placeholder of a text with its value. */
export function fillText(text: string, values: Record<string, string>): string {
	return text.replace(/\{(\w+)\}/g, (placeholder, key: string) => values[key] ?? placeholder)
}
